import pandas as pd
import numpy as np
import os

from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

# ------------------------------------------------------------
# 1. Load the data
# ------------------------------------------------------------
DATA_PATH = "/content/processed.cleveland.csv"

if not os.path.exists(DATA_PATH):
    raise FileNotFoundError(
        f"الملف غير موجود في {DATA_PATH}. تأكد أنك رفعته بـ files.upload()"
    )

df = pd.read_csv(DATA_PATH, sep=';', na_values='?')
print("Original shape:", df.shape)
print(df.head())

# ------------------------------------------------------------
# 2. Binarize the target
# ------------------------------------------------------------
df['num'] = (df['num'] > 0).astype(int)
print("\nTarget distribution:\n", df['num'].value_counts())

# ------------------------------------------------------------
# 3. Feature groups
# ------------------------------------------------------------
numeric_features = ['age', 'trestbps', 'chol', 'thalach', 'oldpeak']
binary_features  = ['sex', 'fbs', 'exang']
nominal_features = ['cp', 'restecg', 'slope', 'thal']
count_features   = ['ca']

X = df.drop(columns=['num'])
y = df['num']

# ------------------------------------------------------------
# 4. Preprocessing pipeline
# ------------------------------------------------------------
preprocessor = ColumnTransformer(
    transformers=[
        ('num', Pipeline([('imp', SimpleImputer(strategy='median')),
                          ('sc',  StandardScaler())]), numeric_features),
        ('bin', Pipeline([('imp', SimpleImputer(strategy='most_frequent'))]), binary_features),
        ('nom', Pipeline([('imp', SimpleImputer(strategy='most_frequent')),
                          ('oh',  OneHotEncoder(handle_unknown='ignore',
                                                sparse_output=False))]), nominal_features),
        ('cnt', Pipeline([('imp', SimpleImputer(strategy='most_frequent')),
                          ('sc',  StandardScaler())]), count_features),
    ],
    remainder='drop'
)

# ------------------------------------------------------------
# 5. Transform + save
# ------------------------------------------------------------
X_proc = preprocessor.fit_transform(X)
processed_df = pd.DataFrame(X_proc, columns=preprocessor.get_feature_names_out())
processed_df['num'] = y.values

OUT_PATH = "/content/updated.csv"
processed_df.to_csv(OUT_PATH, index=False)

print("\nProcessed shape:", processed_df.shape)
print("Columns:", list(processed_df.columns))
print(f"\n✅ تم حفظ الملف في: {OUT_PATH}")

